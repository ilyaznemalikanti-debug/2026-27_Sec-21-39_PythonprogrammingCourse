#Set Creation and Basic Operations (Union, Intersection, Difference)
# Create two sets
A = {10, 20, 30, 40}
B = {30, 40, 50, 60}

print("Set A:", A)
print("Set B:", B)

# Union
print("Union:", A | B)

# Intersection
print("Intersection:", A & B)

# Difference
print("Difference:", A - B)